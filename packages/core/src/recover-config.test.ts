import { describe, expect, it } from 'vitest'
import { loadGcodeText } from './gcode-file.ts'
import { inspectGcode } from './process.ts'
import { ConfigSource, recoverTowerConfig } from './recover-config.ts'
import { Material } from './tower-config.ts'

const name = 'temptower_v1_PLA_230to190_step5_h10_b2_m104'
const expected = {
  material: Material.PLA,
  startTemperature: 230,
  endTemperature: 190,
  step: 5,
  blockHeight: 10,
  baseHeight: 2,
  waitForTemperature: false,
}

describe('config recovery (ADR-0005)', () => {
  it('reads the config from a G-code name that keeps the STL base name', () => {
    expect(recoverTowerConfig(`${name}_0.2mm_PLA_MK3S_1h5m.gcode`, [])).toEqual({ config: expected, source: ConfigSource.FILENAME })
  })

  it('falls back to the object label when the G-code was renamed', () => {
    const text = ['; generated by PrusaSlicer 2.8.0', 'M486 S0', `M486 A${name}.stl`, 'G1 X1 E1'].join('\n')
    expect(inspectGcode(loadGcodeText('renamed.gcode', text)).recovered).toEqual({ config: expected, source: ConfigSource.OBJECT_LABEL })
    const legacy = ['; generated by PrusaSlicer 2.6.0', `; printing object ${name}.stl id:0 copy 0`, 'G1 X1 E1'].join('\n')
    expect(inspectGcode(loadGcodeText('renamed.gcode', legacy)).recovered?.source).toBe(ConfigSource.OBJECT_LABEL)
    const klipper = ['; generated by PrusaSlicer 2.8.0', `EXCLUDE_OBJECT_DEFINE NAME=${name}.stl_id_0_copy_0 CENTER=1,2`, 'G1 X1 E1'].join('\n')
    expect(inspectGcode(loadGcodeText('renamed.gcode', klipper)).recovered?.source).toBe(ConfigSource.OBJECT_LABEL)
  })

  it('returns null for manual entry when neither carries a config', () => {
    const text = ['; generated by PrusaSlicer 2.8.0', 'M486 Abenchy.stl', 'G1 X1 E1'].join('\n')
    expect(inspectGcode(loadGcodeText('benchy_0.2mm.gcode', text)).recovered).toBeNull()
  })
})
