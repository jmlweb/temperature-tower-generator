import { Material, type TowerConfig } from './tower-config.ts'
import { countTierCommands, NEUTRALIZED_PREFIX, planTiers, TemperatureDialect, temperatureDialect, tierMarkerLine, transformGcode } from './transform.ts'
import { MARKER } from './version.ts'

const config: TowerConfig = {
  material: Material.PLA,
  startTemperature: 230,
  endTemperature: 220,
  step: 5,
  blockHeight: 6,
  baseHeight: 1,
  waitForTemperature: false,
}

/** A tower-like file: start G-code, then one extruding move per 0.2 mm layer up to `top`. */
const towerGcode = (top: number, extra: (z: number) => string[] = () => []): string => {
  const lines = ['; generated by PrusaSlicer 2.8.0', 'M104 S215 ; start', 'M109 S215 ; start', 'G90', 'M83', 'G28']
  let layer = 0
  for (let z = 0.2; z <= top + 0.0001; z = Math.round((z + 0.2) * 1000) / 1000) {
    lines.push(`G1 Z${z}`, ...extra(z), `G1 X${layer % 2 === 0 ? 10 : 20} Y10 E1 ; layer at ${z}`)
    layer += 1
  }
  lines.push('M104 S0 ; turn off', 'M140 S0')
  return lines.join('\n')
}

const run = (text: string, towerConfig = config) => {
  const lines = parseGcode(text)
  return transformGcode({ lines, motion: analyzeMotion(lines), config: towerConfig })
}

describe('transform', () => {
  it('inserts one tier command before the first layer of each tier', () => {
    const result = run(towerGcode(19))
    const inserted = result.changes.filter((c) => c.kind === 'insert')
    expect(inserted.map((c) => c.text)).toEqual([
      `M109 R230 ${MARKER} tier 0`,
      `M104 S225 ${MARKER} tier 1`,
      `M104 S220 ${MARKER} tier 2`,
    ])
    expect(result.tiers.map((t) => t.startZ)).toEqual([0, 7, 13])
    expect(result.tiers.map((t) => t.layerZ)).toEqual([0.2, 7.2, 13.2])
    const outputLines = result.text.split('\n')
    const tier1 = outputLines.indexOf(`M104 S225 ${MARKER} tier 1`)
    expect(outputLines[tier1 + 1]).toBe('G1 X20 Y10 E1 ; layer at 7.2')
  })

  it('starts tier 0 at the first extruding move of the file, waiting, so the base prints at its temperature (ADR-0009)', () => {
    const result = run(towerGcode(19))
    const outputLines = result.text.split('\n')
    const tier0 = outputLines.indexOf(`M109 R230 ${MARKER} tier 0`)
    expect(outputLines[tier0 - 1]).toBe('G1 Z0.2')
    expect(outputLines[tier0 + 1]).toBe('G1 X10 Y10 E1 ; layer at 0.2')
  })

  it('uses M109 for tiers 1 and up when the config waits for temperature', () => {
    const result = run(towerGcode(19), { ...config, waitForTemperature: true })
    expect(result.changes.filter((c) => c.kind === 'insert').map((c) => c.text.split(' ')[0])).toEqual(['M109', 'M109', 'M109'])
  })

  it('neutralizes temperature commands after the tier 0 command, keeps start G-code and turn-off (ADR-0009)', () => {
    const result = run(towerGcode(19, (z) => (z === 0.6 || z === 7 ? [`M104 S200 ; slicer at ${z}`] : [])))
    const neutralized = result.changes.filter((c) => c.kind === 'neutralize')
    expect(neutralized.map((c) => c.original)).toEqual(['M104 S200 ; slicer at 0.6', 'M104 S200 ; slicer at 7'])
    expect(result.text).toContain('\nM104 S215 ; start\n')
    expect(result.text).toContain('\nM109 S215 ; start\n')
    expect(result.text).toContain('\nM104 S0 ; turn off\n')
    expect(result.text).toContain(`\n${NEUTRALIZED_PREFIX}M104 S200 ; slicer at 0.6\n`)
  })

  it('neutralizes a temperature command without a target after tier 0, as before', () => {
    const result = run(towerGcode(19, (z) => (z === 3 ? ['M104 T0'] : [])))
    expect(result.changes.filter((c) => c.kind === 'neutralize').map((c) => c.original)).toEqual(['M104 T0'])
  })

  it('neutralizes tool-indexed variants too', () => {
    const result = run(towerGcode(19, (z) => (z === 13 ? ['M109 T0 S210'] : [])))
    expect(result.changes.filter((c) => c.kind === 'neutralize').map((c) => c.original)).toEqual(['M109 T0 S210'])
  })

  it('starts the output with the header block', () => {
    const result = run(towerGcode(19))
    const head = result.text.split('\n').slice(0, 4)
    expect(head.every((line) => line.startsWith(MARKER))).toBe(true)
    expect(head[1]).toBe(`${MARKER} config: temptower_v1_PLA_230to220_step5_h6_b1_m104`)
    expect(head[2]).toBe(`${MARKER} tiers: 3 x 6 mm on a 1 mm base (230 to 220 C, step 5, tier 0 M109 wait, tiers 1+ M104 no wait)`)
    expect(head[3]).toContain('3 tier commands inserted, 0 temperature commands neutralized')
  })

  it('waits with M109 S on Klipper, which reads only S (ADR-0012)', () => {
    const lines = parseGcode(towerGcode(19))
    const waiting = { ...config, waitForTemperature: true }
    const inline = transformGcode({ lines, motion: analyzeMotion(lines), config: waiting, dialect: TemperatureDialect.KLIPPER })
    expect(inline.changes.filter((c) => c.kind === 'insert').map((c) => c.text)).toEqual([
      `M109 S230 ${MARKER} tier 0`,
      `M109 S225 ${MARKER} tier 1`,
      `M109 S220 ${MARKER} tier 2`,
    ])
    const line = transformGcode({ lines, motion: analyzeMotion(lines), config, markerStyle: 'line', dialect: TemperatureDialect.KLIPPER })
    expect(line.changes.filter((c) => c.kind === 'insert').map((c) => c.text)).toEqual([tierMarkerLine(0), 'M109 S230', tierMarkerLine(1), 'M104 S225', tierMarkerLine(2), 'M104 S220'])
    expect(inline.text).not.toMatch(/M109 R/)
  })

  it('picks the dialect from gcode_flavor (ADR-0012)', () => {
    expect(temperatureDialect('klipper')).toBe(TemperatureDialect.KLIPPER)
    expect(temperatureDialect(' Klipper ')).toBe(TemperatureDialect.KLIPPER)
    expect(temperatureDialect('marlin2')).toBe(TemperatureDialect.MARLIN)
    expect(temperatureDialect(undefined)).toBe(TemperatureDialect.MARLIN)
  })

  it('puts the tier marker on its own line when asked, for binary output (ADR-0007)', () => {
    const lines = parseGcode(towerGcode(19))
    const result = transformGcode({ lines, motion: analyzeMotion(lines), config, markerStyle: 'line' })
    const inserted = result.changes.filter((c) => c.kind === 'insert').map((c) => c.text)
    expect(inserted).toEqual([tierMarkerLine(0), 'M109 R230', tierMarkerLine(1), 'M104 S225', tierMarkerLine(2), 'M104 S220'])
    expect(result.text).toContain(`\n${MARKER} tier 1\nM104 S225\nG1 X20 Y10 E1 ; layer at 7.2\n`)
    expect(countTierCommands(result.tiers)).toBe(3)
    expect(result.text).toContain('3 tier commands inserted')
  })

  it('leaves tiers unplaced when the model is too short', () => {
    const lines = parseGcode(towerGcode(8))
    const tiers = planTiers(config, analyzeMotion(lines).layers)
    expect(tiers.map((t) => t.lineIndex === null)).toEqual([false, false, true])
  })
})

const lineArbitrary = fc.oneof(
  fc.constant(''),
  fc.constant('G90'),
  fc.constant('G91'),
  fc.constant('M82'),
  fc.constant('M83'),
  fc.constant('G92 E0'),
  fc.constant(';LAYER_CHANGE'),
  fc.constant('M104 S0'),
  fc.constant('M107 ; fan off'),
  fc.integer({ min: 150, max: 260 }).map((s) => `M104 S${s}`),
  fc.integer({ min: 150, max: 260 }).map((s) => `M109 T0 S${s} ; wait`),
  fc.tuple(fc.integer({ min: 0, max: 200 }), fc.integer({ min: 0, max: 200 }), fc.integer({ min: -20, max: 50 })).map(
    ([x, y, e]) => `G1 X${x} Y${y} E${e / 10}`,
  ),
  fc.integer({ min: 0, max: 600 }).map((z) => `G1 Z${z / 10}`),
  fc.string({ minLength: 0, maxLength: 12 }).filter((s) => !/[\n\r]/.test(s) && !s.startsWith('[temptower]')).map((s) => `; ${s}`),
)

const endingArbitrary = fc.constantFrom('\n', '\r\n')

const configArbitrary: fc.Arbitrary<TowerConfig> = fc.record({
  material: fc.constantFrom(...Object.values(Material)),
  startTemperature: fc.integer({ min: 180, max: 260 }),
  endTemperature: fc.integer({ min: 180, max: 260 }),
  step: fc.integer({ min: 3, max: 10 }),
  blockHeight: fc.integer({ min: 6, max: 15 }),
  baseHeight: fc.integer({ min: 1, max: 4 }),
  waitForTemperature: fc.boolean(),
}).filter((c) => c.startTemperature !== c.endTemperature)

const dialectArbitrary = fc.constantFrom(...Object.values(TemperatureDialect))

const TIER_SUFFIX = new RegExp(` ${MARKER.replaceAll('[', '\\[').replaceAll(']', '\\]')} tier (\\d+)$`)

describe('line-preserving property (ADR-0002)', () => {
  test.prop([fc.array(lineArbitrary, { maxLength: 80 }), endingArbitrary, configArbitrary, dialectArbitrary])(
    'every output line is an untouched input line, an inserted tier command, a header, or a neutralized input line',
    (inputLines, ending, towerConfig, dialect) => {
      const input = inputLines.join(ending)
      const parsed = parseGcode(input)
      const result = transformGcode({ lines: parsed, motion: analyzeMotion(parsed), config: towerConfig, dialect })

      // A file with fewer than two lines has no detectable ending, so split on both.
      const outputLines = result.text.split(/\r\n|\n/)
      const recovered: string[] = []
      for (const line of outputLines) {
        if (line.startsWith(`${MARKER} `) && !line.startsWith(NEUTRALIZED_PREFIX)) continue
        if (TIER_SUFFIX.test(line)) {
          expect(line).toMatch(dialect === TemperatureDialect.KLIPPER ? /^(M109|M104) S\d+ / : /^(M109 R|M104 S)\d+ /)
          continue
        }
        if (line.startsWith(NEUTRALIZED_PREFIX)) {
          const original = line.slice(NEUTRALIZED_PREFIX.length)
          expect(original).toMatch(/^\s*M10[49]\b/i)
          recovered.push(original)
          continue
        }
        recovered.push(line)
      }
      expect(recovered.join('\n')).toBe(inputLines.join('\n'))
      expect(result.text.startsWith(`${MARKER} `)).toBe(true)
    },
  )
})

/** A minimal binary file around `text`, in PrusaSlicer's default encoding. */
const binaryFile = (text: string, printer: Record<string, string> = { printer_model: 'COREONE' }): Uint8Array =>
  concatBytes([
    writeFileHeader(ChecksumType.CRC32),
    writeBlock({ type: BgcodeBlockType.FILE_METADATA, compression: BgcodeCompression.NONE, parameters: encodingParameters(MetadataEncoding.INI), data: formatIni({ Producer: 'PrusaSlicer 2.9.0' }) }, ChecksumType.CRC32),
    writeBlock({ type: BgcodeBlockType.PRINTER_METADATA, compression: BgcodeCompression.NONE, parameters: encodingParameters(MetadataEncoding.INI), data: formatIni(printer) }, ChecksumType.CRC32),
    ...splitGcodeChunks(utf8Encode(text)).map((chunk) =>
      writeBlock({ type: BgcodeBlockType.GCODE, compression: BgcodeCompression.HEATSHRINK_12_4, parameters: encodingParameters(GcodeEncoding.MEATPACK_COMMENTS), data: meatpackEncode(chunk, { removeComments: false }) }, ChecksumType.CRC32),
    ),
  ])

const TIER_MARKER_LINE = new RegExp(`^${MARKER.replaceAll('[', '\\[').replaceAll(']', '\\]')} tier (\\d+)$`)

describe('line-preserving property over binary G-code (ADR-0007)', () => {
  test.prop([fc.array(lineArbitrary, { maxLength: 80 }), configArbitrary, dialectArbitrary])(
    'every decoded output line is a decoded input line, a marker line plus its command, a header, or a neutralized line',
    (inputLines, towerConfig, dialect) => {
      // The input goes through MeatPack once, as a slicer export would, so the decoded text is the canonical form.
      const input = decodeBgcode(binaryFile(inputLines.length === 0 ? '' : `${inputLines.join('\n')}\n`))
      const parsed = parseGcode(input.text)
      const result = transformGcode({ lines: parsed, motion: analyzeMotion(parsed), config: towerConfig, markerStyle: 'line', dialect })
      const output = decodeBgcode(encodeBgcode(input, result.text))

      const outputLines = output.text.split('\n')
      const recovered: string[] = []
      let expectCommand = false
      for (const line of outputLines) {
        if (expectCommand) {
          expect(line).toMatch(dialect === TemperatureDialect.KLIPPER ? /^(M109|M104) S\d+$/ : /^(M109 R|M104 S)\d+$/)
          expectCommand = false
          continue
        }
        if (TIER_MARKER_LINE.test(line)) {
          expectCommand = true
          continue
        }
        if (line.startsWith(`${MARKER} `) && !line.startsWith(NEUTRALIZED_PREFIX)) continue
        if (line.startsWith(NEUTRALIZED_PREFIX)) {
          const original = line.slice(NEUTRALIZED_PREFIX.length)
          expect(original).toMatch(/^\s*M10[49]\b/i)
          recovered.push(original)
          continue
        }
        recovered.push(line)
      }
      expect(recovered.join('\n')).toBe(input.text.split('\n').join('\n'))
      expect(output.text.startsWith(`${MARKER} `)).toBe(true)
    },
  )
})

describe('dialect from the slicer config (ADR-0012)', () => {
  const tierZero = (bytes: Uint8Array, fileName: string): string | undefined =>
    processGcode({ file: loadGcodeFile({ fileName, bytes }), config }).report.inserted.find((line) => /^M109 /.test(line.text))?.text

  it('waits with M109 S when binary printer metadata says gcode_flavor = klipper', () => {
    const text = `${towerGcode(19)}\n`
    expect(tierZero(binaryFile(text, { printer_model: 'COREONE', gcode_flavor: 'klipper' }), 'tower.bgcode')).toBe('M109 S230')
    expect(tierZero(binaryFile(text, { printer_model: 'COREONE', gcode_flavor: 'marlin2' }), 'tower.bgcode')).toBe('M109 R230')
  })

  it('waits with M109 S when the plain config block says gcode_flavor = klipper', () => {
    const withFlavor = (flavor: string) => utf8Encode(`${towerGcode(19)}\n; gcode_flavor = ${flavor}\n`)
    expect(tierZero(withFlavor('klipper'), 'tower.gcode')).toBe(`M109 S230 ${MARKER} tier 0`)
    expect(tierZero(withFlavor('marlin'), 'tower.gcode')).toBe(`M109 R230 ${MARKER} tier 0`)
  })
})

/**
 * Undoes the three ADR-0002 changes on raw output bytes: drops header and
 * inserted tier lines and unwraps neutralized lines. Latin-1 maps each byte to
 * one code point, so string work here is byte work.
 */
const recoverInputBytes = (output: Uint8Array): Uint8Array => {
  const kept = latin1Decode(output)
    .split('\n')
    .filter((line) => !/^(?:; \[temptower\] (?!neutralized: ).*|.* ; \[temptower\] tier \d+)\r?$/.test(line))
    .map((line) => (line.startsWith(NEUTRALIZED_PREFIX) ? line.slice(NEUTRALIZED_PREFIX.length) : line))
  return latin1Encode(kept.join('\n'))
}

const rawCommentArbitrary = fc
  .uint8Array({ minLength: 1, maxLength: 12 })
  .map((bytes) => new Uint8Array([0x3b, 0x20, ...bytes.filter((b) => b !== 0x0a && b !== 0x0d)]))

describe('line-preserving property over raw bytes (ADR-0002, RPT-006)', () => {
  test.prop([fc.array(fc.oneof(lineArbitrary.map((line) => utf8Encode(line)), rawCommentArbitrary), { maxLength: 80 }), endingArbitrary, configArbitrary])(
    'every input byte outside the changed lines reaches the output unchanged, valid UTF-8 or not',
    (inputLines, ending, towerConfig) => {
      const endingBytes = utf8Encode(ending)
      const bytes = new Uint8Array(inputLines.flatMap((line, i) => [...(i === 0 ? [] : endingBytes), ...line]))
      const file = loadGcodeFile({ fileName: 'tower.gcode', bytes })
      const parsed = parseGcode(file.text)
      const result = transformGcode({ lines: parsed, motion: analyzeMotion(parsed), config: towerConfig })
      expect([...recoverInputBytes(encodePlainText(result.text, file.textEncoding))]).toEqual([...bytes])
    },
  )

  it('keeps a Latin-1 byte in a comment line of a plain upload', () => {
    const bytes = new Uint8Array([...utf8Encode('; caf'), 0xe9, ...utf8Encode(` note\n${towerGcode(19)}\n`)])
    const file = loadGcodeFile({ fileName: 'tower.gcode', bytes })
    expect(file.textEncoding).toBe(TextEncoding.LATIN1)
    const output = processGcode({ file, config }).outputBytes!
    expect(output.includes(0xe9)).toBe(true)
    expect(latin1Decode(output)).toContain('; café note\n')
    expect([...recoverInputBytes(output)]).toEqual([...bytes])
  })

  it.each([
    ['empty', [], TextEncoding.UTF8],
    ['a BOM', [0xef, 0xbb, 0xbf, 0x3b], TextEncoding.UTF8],
    ['a literal U+FFFD', [0x3b, 0xef, 0xbf, 0xbd], TextEncoding.UTF8],
    ['a truncated sequence', [0x3b, 0xe2, 0x82], TextEncoding.LATIN1],
    ['an encoded surrogate', [0x3b, 0xed, 0xa0, 0x80], TextEncoding.LATIN1],
  ] as const)('reads %s input as %s and writes the same bytes back', (_, input, encoding) => {
    const bytes = new Uint8Array(input)
    const file = loadGcodeFile({ fileName: 'tower.gcode', bytes })
    expect(file.textEncoding).toBe(encoding)
    expect([...encodePlainText(file.text, file.textEncoding)]).toEqual([...bytes])
  })

  it('keeps UTF-8 decoding for valid UTF-8, multi-byte names included', () => {
    const file = loadGcodeFile({ fileName: 'tower.gcode', bytes: utf8Encode(`; café \u{1F600}\n${towerGcode(19)}\n`) })
    expect(file.textEncoding).toBe(TextEncoding.UTF8)
    expect(file.text.startsWith('; café \u{1F600}\n')).toBe(true)
  })
})
