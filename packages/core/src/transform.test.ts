import { fc, test } from '@fast-check/vitest'
import { describe, expect, it } from 'vitest'
import { parseGcode } from './gcode-lines.ts'
import { analyzeMotion } from './motion.ts'
import { Material, type TowerConfig } from './tower-config.ts'
import { NEUTRALIZED_PREFIX, planTiers, transformGcode } from './transform.ts'
import { MARKER } from './version.ts'

const config: TowerConfig = {
  material: Material.PLA,
  startTemperature: 230,
  endTemperature: 220,
  step: 5,
  blockHeight: 6,
  baseHeight: 1,
  waitForTemperature: false,
}

/** A tower-like file: start G-code, then one extruding move per 0.2 mm layer up to `top`. */
const towerGcode = (top: number, extra: (z: number) => string[] = () => []): string => {
  const lines = ['; generated by PrusaSlicer 2.8.0', 'M104 S215 ; start', 'M109 S215 ; start', 'G90', 'M83', 'G28']
  let layer = 0
  for (let z = 0.2; z <= top + 0.0001; z = Math.round((z + 0.2) * 1000) / 1000) {
    lines.push(`G1 Z${z}`, ...extra(z), `G1 X${layer % 2 === 0 ? 10 : 20} Y10 E1 ; layer at ${z}`)
    layer += 1
  }
  lines.push('M104 S0 ; turn off', 'M140 S0')
  return lines.join('\n')
}

const run = (text: string, towerConfig = config) => {
  const lines = parseGcode(text)
  return transformGcode({ lines, motion: analyzeMotion(lines), config: towerConfig })
}

describe('transform', () => {
  it('inserts one tier command before the first layer of each tier', () => {
    const result = run(towerGcode(19))
    const inserted = result.changes.filter((c) => c.kind === 'insert')
    expect(inserted.map((c) => c.text)).toEqual([
      `M104 S230 ${MARKER} tier 0`,
      `M104 S225 ${MARKER} tier 1`,
      `M104 S220 ${MARKER} tier 2`,
    ])
    expect(result.tiers.map((t) => t.layerZ)).toEqual([1, 7, 13])
    const outputLines = result.text.split('\n')
    const tier1 = outputLines.indexOf(`M104 S225 ${MARKER} tier 1`)
    expect(outputLines[tier1 + 1]).toBe('G1 X10 Y10 E1 ; layer at 7')
  })

  it('uses M109 when the config waits for temperature', () => {
    const result = run(towerGcode(19), { ...config, waitForTemperature: true })
    expect(result.changes.find((c) => c.kind === 'insert')?.text).toBe(`M109 S230 ${MARKER} tier 0`)
  })

  it('neutralizes temperature commands at or above the first tier, keeps start G-code and turn-off', () => {
    const result = run(towerGcode(19, (z) => (z === 0.6 || z === 7 ? [`M104 S200 ; slicer at ${z}`] : [])))
    const neutralized = result.changes.filter((c) => c.kind === 'neutralize')
    expect(neutralized.map((c) => c.original)).toEqual(['M104 S200 ; slicer at 7'])
    expect(result.text).toContain('\nM104 S215 ; start\n')
    expect(result.text).toContain('\nM104 S200 ; slicer at 0.6\n')
    expect(result.text).toContain('\nM104 S0 ; turn off\n')
    expect(result.text).toContain(`\n${NEUTRALIZED_PREFIX}M104 S200 ; slicer at 7\n`)
  })

  it('neutralizes tool-indexed variants too', () => {
    const result = run(towerGcode(19, (z) => (z === 13 ? ['M109 T0 S210'] : [])))
    expect(result.changes.filter((c) => c.kind === 'neutralize').map((c) => c.original)).toEqual(['M109 T0 S210'])
  })

  it('starts the output with the header block', () => {
    const result = run(towerGcode(19))
    const head = result.text.split('\n').slice(0, 4)
    expect(head.every((line) => line.startsWith(MARKER))).toBe(true)
    expect(head[1]).toBe(`${MARKER} config: temptower_v1_PLA_230to220_step5_h6_b1_m104`)
    expect(head[3]).toContain('3 tier commands inserted, 0 temperature commands neutralized')
  })

  it('leaves tiers unplaced when the model is too short', () => {
    const lines = parseGcode(towerGcode(8))
    const tiers = planTiers(config, analyzeMotion(lines).layers)
    expect(tiers.map((t) => t.lineIndex === null)).toEqual([false, false, true])
  })
})

const lineArbitrary = fc.oneof(
  fc.constant(''),
  fc.constant('G90'),
  fc.constant('G91'),
  fc.constant('M82'),
  fc.constant('M83'),
  fc.constant('G92 E0'),
  fc.constant(';LAYER_CHANGE'),
  fc.constant('M104 S0'),
  fc.constant('M107 ; fan off'),
  fc.integer({ min: 150, max: 260 }).map((s) => `M104 S${s}`),
  fc.integer({ min: 150, max: 260 }).map((s) => `M109 T0 S${s} ; wait`),
  fc.tuple(fc.integer({ min: 0, max: 200 }), fc.integer({ min: 0, max: 200 }), fc.integer({ min: -20, max: 50 })).map(
    ([x, y, e]) => `G1 X${x} Y${y} E${e / 10}`,
  ),
  fc.integer({ min: 0, max: 600 }).map((z) => `G1 Z${z / 10}`),
  fc.string({ minLength: 0, maxLength: 12 }).filter((s) => !/[\n\r]/.test(s) && !s.startsWith('[temptower]')).map((s) => `; ${s}`),
)

const endingArbitrary = fc.constantFrom('\n', '\r\n')

const configArbitrary: fc.Arbitrary<TowerConfig> = fc.record({
  material: fc.constantFrom(Material.PLA, Material.PETG, Material.CUSTOM),
  startTemperature: fc.integer({ min: 180, max: 260 }),
  endTemperature: fc.integer({ min: 180, max: 260 }),
  step: fc.integer({ min: 3, max: 10 }),
  blockHeight: fc.integer({ min: 6, max: 15 }),
  baseHeight: fc.integer({ min: 1, max: 4 }),
  waitForTemperature: fc.boolean(),
}).filter((c) => c.startTemperature !== c.endTemperature)

const TIER_SUFFIX = new RegExp(` ${MARKER.replaceAll('[', '\\[').replaceAll(']', '\\]')} tier (\\d+)$`)

describe('line-preserving property (ADR-0002)', () => {
  test.prop([fc.array(lineArbitrary, { maxLength: 80 }), endingArbitrary, configArbitrary])(
    'every output line is an untouched input line, an inserted tier command, a header, or a neutralized input line',
    (inputLines, ending, towerConfig) => {
      const input = inputLines.join(ending)
      const parsed = parseGcode(input)
      const result = transformGcode({ lines: parsed, motion: analyzeMotion(parsed), config: towerConfig })

      // A file with fewer than two lines has no detectable ending, so split on both.
      const outputLines = result.text.split(/\r\n|\n/)
      const recovered: string[] = []
      for (const line of outputLines) {
        if (line.startsWith(`${MARKER} `) && !line.startsWith(NEUTRALIZED_PREFIX)) continue
        if (TIER_SUFFIX.test(line)) continue
        if (line.startsWith(NEUTRALIZED_PREFIX)) {
          const original = line.slice(NEUTRALIZED_PREFIX.length)
          expect(original).toMatch(/^\s*M10[49]\b/i)
          recovered.push(original)
          continue
        }
        recovered.push(line)
      }
      expect(recovered.join('\n')).toBe(inputLines.join('\n'))
      expect(result.text.startsWith(`${MARKER} `)).toBe(true)
    },
  )
})
