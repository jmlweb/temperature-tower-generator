import type { GcodeLine } from '../gcode-lines.ts'
import type { LayerMarker, SlicerInfo, SlicerMetadata, SlicerReader } from './types.ts'

const GENERATED_BY = /^\s*generated by PrusaSlicer\s+(\S+)/i
const PRODUCER = /^PrusaSlicer\s+(\S+)/i
const CONFIG_LINE = /^\s*([a-z][a-z0-9_]*)\s*=\s*(.*)$/
const LAYER_Z = /^Z:\s*([-+]?\d*\.?\d+)/
const PRINTING_OBJECT = /^\s*printing object\s+(.+?)\s+id:\d+/

const parseNumber = (value: string | undefined): number | null => {
  if (value === undefined) return null
  const n = Number.parseFloat(value)
  return Number.isFinite(n) ? n : null
}

/** Reads the first value of a possibly per-extruder list such as `215,220`. */
const parseFirstNumber = (value: string | undefined): number | null =>
  parseNumber(value?.split(',')[0])

const parseBoolean = (value: string | undefined): boolean | null => {
  if (value === undefined) return null
  if (value === '1' || value === 'true') return true
  if (value === '0' || value === 'false') return false
  return null
}

/** Raw instance names, copies included, so two copies of one STL count as two objects. */
const collectObjectNames = (lines: readonly GcodeLine[], objectsInfo: string | undefined): readonly string[] => {
  const names = new Set<string>()
  for (const line of lines) {
    // Marlin M486 A<name>; PrusaSlicer writes the name right after the letter.
    if (line.code === 'M486') {
      const match = /^M486\s+A(.+)$/i.exec(line.raw.split(';')[0]!.trim())
      if (match) names.add(match[1]!.trim())
      continue
    }
    if (line.code === null && line.raw.toUpperCase().startsWith('EXCLUDE_OBJECT_DEFINE')) {
      const match = /NAME=(\S+)/i.exec(line.raw)
      if (match) names.add(match[1]!.trim())
      continue
    }
    if (line.comment === null) continue
    const printing = PRINTING_OBJECT.exec(line.comment)
    if (printing) names.add(printing[1]!.trim())
  }
  if (objectsInfo !== undefined) {
    try {
      const parsed = JSON.parse(objectsInfo) as { objects?: { name?: string }[] }
      for (const object of parsed.objects ?? []) {
        if (typeof object.name === 'string') names.add(object.name.trim())
      }
    } catch {
      // Malformed JSON in a comment is not our problem; motion state still decides.
    }
  }
  return [...names]
}

const collectLayerMarkers = (lines: readonly GcodeLine[]): readonly LayerMarker[] => {
  const markers: LayerMarker[] = []
  let pendingChange = false
  for (const line of lines) {
    if (line.comment === null || line.code !== null) continue
    const comment = line.comment.trim()
    if (comment === 'LAYER_CHANGE') {
      pendingChange = true
      continue
    }
    if (!pendingChange) continue
    const match = LAYER_Z.exec(comment)
    if (match) {
      markers.push({ lineIndex: line.index, z: Number(match[1]) })
      pendingChange = false
    }
  }
  return markers
}

const collectConfig = (lines: readonly GcodeLine[]): Record<string, string> => {
  const config: Record<string, string> = {}
  for (const line of lines) {
    if (line.code !== null || line.comment === null) continue
    const match = CONFIG_LINE.exec(line.comment)
    if (match) config[match[1]!] = match[2]!.trim()
  }
  return config
}

/**
 * Binary G-code moves the `; key = value` block into metadata blocks (ADR-0007);
 * merging them under the comment-derived values gives both inputs one config map.
 */
const mergeConfig = (lines: readonly GcodeLine[], metadata: SlicerMetadata): Record<string, string> => ({
  ...(metadata?.slicer ?? {}),
  ...(metadata?.printer ?? {}),
  ...(metadata?.print ?? {}),
  ...collectConfig(lines),
})

const versionFromHeader = (lines: readonly GcodeLine[]): string | null =>
  lines
    .slice(0, 5)
    .map((line) => GENERATED_BY.exec(line.comment ?? ''))
    .find(Boolean)?.[1] ?? null

const versionFromMetadata = (metadata: SlicerMetadata): string | null => PRODUCER.exec(metadata?.file.Producer ?? '')?.[1] ?? null

export const prusaSlicerReader: SlicerReader = {
  name: 'PrusaSlicer',
  detect: (lines, metadata) => versionFromMetadata(metadata) !== null || versionFromHeader(lines) !== null,
  read: (lines, metadata) => {
    const config = mergeConfig(lines, metadata)
    return {
      slicer: 'PrusaSlicer',
      version: versionFromMetadata(metadata) ?? versionFromHeader(lines),
      temperature: parseFirstNumber(config.temperature),
      firstLayerTemperature: parseFirstNumber(config.first_layer_temperature),
      filamentType: config.filament_type?.split(';')[0]?.trim() ?? null,
      layerHeight: parseNumber(config.layer_height),
      firstLayerHeight: parseNumber(config.first_layer_height),
      completeObjects: parseBoolean(config.complete_objects),
      printerModel: config.printer_model ?? null,
      objectNames: collectObjectNames(lines, config.objects_info),
      layerMarkers: collectLayerMarkers(lines),
      config,
    }
  },
}
