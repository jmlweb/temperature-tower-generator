import { describe, expect, it } from 'vitest'
import { parseGcode } from '../gcode-lines.ts'
import { prusaSlicerReader } from './prusaslicer.ts'

const label = 'temptower_v1_PLA_230to220_step5_h6_b1_m104'
const objectsInfo = (...names: string[]): string => `; objects_info = ${JSON.stringify({ objects: names.map((name) => ({ name, polygon: [[0, 0]] })) })}`
const objectNames = (lines: string[]): readonly string[] => prusaSlicerReader.read(parseGcode(['; generated by PrusaSlicer 2.8.0', ...lines].join('\n')), null).objectNames

describe('PrusaSlicer object names (RPT-008)', () => {
  it('reads one object from quoted Klipper labels plus objects_info', () => {
    const names = objectNames([`EXCLUDE_OBJECT_DEFINE NAME='${label}_stl' CENTER=1,2 POLYGON=[[0,0],[1,1]]`, 'G1 X1 E1', objectsInfo(`${label}_stl`)])
    expect(names).toEqual([`${label}_stl`])
  })

  it('reads one object from OctoPrint-style labels plus objects_info', () => {
    const names = objectNames([`; printing object ${label}.stl id:0 copy 0`, 'G1 X1 E1', `; stop printing object ${label}.stl id:0 copy 0`, objectsInfo(`${label}.stl id:0 copy 0`)])
    expect(names).toEqual([`${label}.stl id:0 copy 0`])
  })

  it('still counts two Klipper instances as two objects', () => {
    const names = objectNames([
      `EXCLUDE_OBJECT_DEFINE NAME='${label}_stl_(Instance_1)' CENTER=1,2`,
      `EXCLUDE_OBJECT_DEFINE NAME='${label}_stl_(Instance_2)' CENTER=3,4`,
      objectsInfo(`${label}_stl_(Instance_1)`, `${label}_stl_(Instance_2)`),
    ])
    expect(names).toHaveLength(2)
  })

  it('still counts two OctoPrint-style copies as two objects', () => {
    const names = objectNames([
      `; printing object ${label}.stl id:1 copy 0`,
      `; printing object ${label}.stl id:1 copy 1`,
      objectsInfo(`${label}.stl id:1 copy 0`, `${label}.stl id:1 copy 1`),
    ])
    expect(names).toHaveLength(2)
  })
})
