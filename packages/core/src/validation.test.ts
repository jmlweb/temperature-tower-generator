import { describe, expect, it } from 'vitest'
import { parseGcode } from './gcode-lines.ts'
import { analyzeMotion } from './motion.ts'
import { readSlicerInfo } from './slicers/registry.ts'
import { Material, type TowerConfig } from './tower-config.ts'
import { ValidationCode, validateGcode } from './validation.ts'

const config: TowerConfig = {
  material: Material.PLA,
  startTemperature: 230,
  endTemperature: 220,
  step: 5,
  blockHeight: 6,
  baseHeight: 1,
  waitForTemperature: false,
}

const towerGcode = (top: number, layerHeight = 0.2, extra: (z: number) => string[] = () => []): string => {
  const lines = ['; generated by PrusaSlicer 2.8.0', 'G90', 'M83']
  let layer = 0
  for (let z = layerHeight; z <= top + 0.0001; z = Math.round((z + layerHeight) * 1000) / 1000) {
    lines.push(';LAYER_CHANGE', `;Z:${z}`, `G1 Z${z}`, ...extra(z), `G1 X${layer % 2 === 0 ? 10 : 20} Y10 E1`)
    layer += 1
  }
  return lines.join('\n')
}

const codes = (text: string, towerConfig = config, binaryError: string | null = null) => {
  const lines = parseGcode(text)
  return validateGcode({ motion: analyzeMotion(lines), slicer: readSlicerInfo(lines), config: towerConfig, binaryError }).map((i) => `${i.severity}:${i.code}`)
}

describe('validation (ADR-0004)', () => {
  it('passes a matching tower', () => {
    expect(codes(towerGcode(19))).toEqual([])
  })

  it('errors on unreadable binary G-code before anything else', () => {
    expect(codes('', config, 'Block 0 checksum mismatch')).toEqual([`error:${ValidationCode.BINARY_GCODE_UNREADABLE}`])
  })

  it('errors when nothing extrudes', () => {
    expect(codes('G1 Z0.2\nG1 X10')).toEqual([`error:${ValidationCode.NO_EXTRUSION}`])
  })

  it('accepts arc moves as ordinary moves (ADR-0008)', () => {
    expect(codes(towerGcode(19, 0.2, (z) => (z === 1 ? ['G2 X12 Y12 I1 J0 E0.1'] : [])))).toEqual([])
  })

  it('errors on variable layer height', () => {
    const text = ['G90', 'M83', 'G1 Z0.2', 'G1 X1 E1', 'G1 Z0.4', 'G1 X2 E1', 'G1 Z0.5', 'G1 X3 E1', 'G1 Z0.7', 'G1 X4 E1', 'G1 Z0.9', 'G1 X5 E1'].join('\n')
    expect(codes(text, { ...config, blockHeight: 6, baseHeight: 1 })).toContain(`error:${ValidationCode.VARIABLE_LAYER_HEIGHT}`)
  })

  it('errors on multiple objects or sequential printing', () => {
    expect(codes(`M486 Aa.stl\nM486 Ab.stl\n${towerGcode(19)}`)).toContain(`error:${ValidationCode.MULTIPLE_OBJECTS}`)
    expect(codes(`${towerGcode(19)}\n; complete_objects = 1`)).toContain(`error:${ValidationCode.MULTIPLE_OBJECTS}`)
    const sequential = `${towerGcode(19)}\nG1 Z0.2\nG1 X50 Y50 E1\nG1 Z0.4\nG1 X51 Y50 E1`
    expect(codes(sequential)).toContain(`error:${ValidationCode.MULTIPLE_OBJECTS}`)
  })

  it('errors when the height is off by more than one layer, warns within one layer', () => {
    expect(codes(towerGcode(17))).toContain(`error:${ValidationCode.HEIGHT_MISMATCH}`)
    expect(codes(towerGcode(19.2))).toEqual([`warning:${ValidationCode.HEIGHT_OFF_BY_ONE_LAYER}`])
  })

  it('warns when tier temperatures leave the preset range', () => {
    expect(codes(towerGcode(19), { ...config, startTemperature: 240, endTemperature: 230 })).toEqual([`warning:${ValidationCode.TEMPERATURE_OUTSIDE_PRESET}`])
    expect(codes(towerGcode(19), { ...config, material: Material.CUSTOM, startTemperature: 300, endTemperature: 290 })).toEqual([])
  })

  it('warns when slicer markers disagree with motion', () => {
    const text = `${towerGcode(19)}\n;LAYER_CHANGE\n;Z:40`
    expect(codes(text)).toEqual([`warning:${ValidationCode.MARKER_MISMATCH}`])
  })

  it('warns when the profile heats the first layer above tier 0 (ADR-0009)', () => {
    const profile = (first: number) => `${towerGcode(19)}\n; first_layer_temperature = ${first}\n; temperature = ${first}`
    expect(codes(profile(235))).toEqual([`warning:${ValidationCode.FIRST_LAYER_ABOVE_TIER_0}`])
    expect(codes(profile(230))).toEqual([])
    expect(codes(`M109 S240\n${towerGcode(19)}`)).toEqual([`warning:${ValidationCode.FIRST_LAYER_ABOVE_TIER_0}`])
  })

  it('warns on multi-tool G-code', () => {
    expect(codes(`T0\n${towerGcode(19)}\nT1`)).toEqual([`warning:${ValidationCode.MULTI_TOOL}`])
  })
})
